        'sentryMainStatus', dataBytes(41));
end

function value = local_read_uint16(bytes, endianMode)
    bytes = uint8(bytes(:));
    if string(endianMode) == "big"
        bytes = flipud(bytes);
    end
    value = typecast(bytes, 'uint16');
end

function values = local_read_uint16_array(bytes, endianMode)
    bytes = uint8(bytes(:));
    n = floor(numel(bytes)/2);
    values = zeros(n, 1, 'uint16');
    for k = 1:n
        idx = 2*k - 1;
        values(k) = local_read_uint16(bytes(idx:idx+1), endianMode);
    end
end

function value = local_read_uint32(bytes, endianMode)
    bytes = uint8(bytes(:));
    if string(endianMode) == "big"
        bytes = flipud(bytes);
    end
    value = typecast(bytes, 'uint32');
end

function tf = local_is_valid_jammer_key(dataBytes)
    chars = char(uint8(dataBytes(:)).');
    tf = numel(chars) == 6 && all(isstrprop(chars, 'alphanum'));
end
