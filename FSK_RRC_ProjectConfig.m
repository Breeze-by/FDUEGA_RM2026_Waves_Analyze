    cfg = struct();
    cfg.paths = struct('rootDir', rootDir);

    cfg.sources = struct( ...
        'redBroadcast', "red_broadcast", ...
        'redL1Jammer', "red_l1_jammer", ...
        'redL2Jammer', "red_l2_jammer", ...
        'redL3Jammer', "red_l3_jammer", ...
        'blueBroadcast', "blue_broadcast", ...
        'blueL1Jammer', "blue_l1_jammer", ...
        'blueL2Jammer', "blue_l2_jammer", ...
        'blueL3Jammer', "blue_l3_jammer", ...
