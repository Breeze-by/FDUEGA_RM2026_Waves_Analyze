        'RxRadioID', "ip:192.168.2.1", ...
        'UseAGC', true, ...
        'AGCMode', "fast", ...                  % 实测邻道强信号下 Fast Attack 削顶更少、增益更稳定
        'RxGain_dB', 20, ...
        'CaptureSampleRateHz', 2.0e6, ...
